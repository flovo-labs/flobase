import { describe, it, expect } from "vitest";
import { Parser } from "node-sql-parser";
import { parseAndValidateSchema } from "../src/schema.js";
import { generatePostgresDDL } from "../src/pg-generator.js";

const FIXTURE_SCHEMA = `
version: "0.1.0"
models:
  User:
    tableName: "users"
    fields:
      id:
        type: uuid
        primary: true
      email:
        type: string
        unique: true
      age:
        type: int
      balance:
        type: decimal
      isActive:
        type: bool
        default: true
      createdAt:
        type: timestamp
        required: true
  Order:
    tableName: "orders"
    fields:
      id:
        type: uuid
        primary: true
      userId:
        type: uuid
        references: "User.id"
      amount:
        type: decimal
        required: true
`;

describe("PostgreSQL DDL Generator", () => {
  const parser = new Parser();

  it("matches deterministic snapshot", () => {
    const parsed = parseAndValidateSchema(FIXTURE_SCHEMA);
    expect(parsed.success).toBe(true);
    const ddl = generatePostgresDDL(parsed.data!);

    expect(ddl).toMatchInlineSnapshot(`
      "-- Generated by Flobase. Do not edit directly.

      CREATE TABLE IF NOT EXISTS users (
        id UUID PRIMARY KEY,
        email TEXT UNIQUE,
        age INTEGER,
        balance NUMERIC(19,4),
        is_active BOOLEAN DEFAULT true,
        created_at TIMESTAMPTZ NOT NULL
      );

      CREATE TABLE IF NOT EXISTS orders (
        id UUID PRIMARY KEY,
        user_id UUID REFERENCES users(id),
        amount NUMERIC(19,4) NOT NULL
      );
      "
    `);
  });

  it("parses as syntactically valid PostgreSQL via node-sql-parser", () => {
    const parsed = parseAndValidateSchema(FIXTURE_SCHEMA);
    expect(parsed.success).toBe(true);
    const ddl = generatePostgresDDL(parsed.data!);

    // Extract CREATE TABLE statements to validate with node-sql-parser
    const statements = ddl
      .split(";")
      .map((s) => s.replace(/-- Generated.*$/m, "").trim())
      .filter((s) => s.length > 0);

    for (const stmt of statements) {
      const ast = parser.astify(stmt, { database: "Postgresql" });
      expect(ast).toBeDefined();
    }
  });

  it("orders dependent tables topologically after referenced tables", () => {
    // Note: Dependent 'Order' is listed before 'User' in YAML
    const unorderedYaml = `
models:
  Order:
    fields:
      id:
        type: uuid
        primary: true
      userId:
        type: uuid
        references: "User.id"
  User:
    fields:
      id:
        type: uuid
        primary: true
`;
    const parsed = parseAndValidateSchema(unorderedYaml);
    expect(parsed.success).toBe(true);
    const ddl = generatePostgresDDL(parsed.data!);

    const userIndex = ddl.indexOf("CREATE TABLE IF NOT EXISTS user");
    const orderIndex = ddl.indexOf("CREATE TABLE IF NOT EXISTS order");
    expect(userIndex).toBeLessThan(orderIndex);
  });
});
