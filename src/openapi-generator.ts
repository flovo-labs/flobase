import * as yaml from "yaml";
import { Flobase, Model, Field } from "./schema.js";

/**
 * Maps Flobase abstract field type to OpenAPI 3.1 schema properties
 */
export function mapFieldToOpenApiProperty(field: Field): Record<string, any> {
  const typeLower = (field.type || "string").toLowerCase();
  const prop: Record<string, any> = {};

  if (field.description) {
    prop.description = field.description;
  }

  if (field.default !== undefined) {
    prop.default = field.default;
  }

  if (field.enum && field.enum.length > 0) {
    prop.type = "string";
    prop.enum = field.enum;
    return prop;
  }

  switch (typeLower) {
    case "uuid":
      prop.type = "string";
      prop.format = "uuid";
      break;
    case "string":
    case "text":
      prop.type = "string";
      break;
    case "int":
    case "integer":
      prop.type = "integer";
      break;
    case "float":
    case "decimal":
      prop.type = "number";
      break;
    case "bool":
    case "boolean":
      prop.type = "boolean";
      break;
    case "datetime":
    case "timestamp":
      prop.type = "string";
      prop.format = "date-time";
      break;
    case "date":
      prop.type = "string";
      prop.format = "date";
      break;
    case "time":
      prop.type = "string";
      prop.format = "time";
      break;
    case "json":
      prop.type = "object";
      break;
    default:
      prop.type = "string";
  }

  return prop;
}

/**
 * Builds OpenAPI component schema for a model
 */
export function buildModelSchema(model: Model, mode: "full" | "create" | "update"): Record<string, any> {
  const properties: Record<string, any> = {};
  const required: string[] = [];

  for (const [fieldName, field] of Object.entries(model.fields || {})) {
    // In create/update modes, primary key is usually generated by DB
    if ((mode === "create" || mode === "update") && (field.primaryKey || field.primary)) {
      continue;
    }

    properties[fieldName] = mapFieldToOpenApiProperty(field);

    if (mode === "create" && (field.required || (!field.nullable && field.default === undefined))) {
      required.push(fieldName);
    } else if (mode === "full" && (field.required || !field.nullable)) {
      required.push(fieldName);
    }
  }

  const schemaDef: Record<string, any> = {
    type: "object",
    properties
  };

  if (required.length > 0) {
    schemaDef.required = required;
  }

  return schemaDef;
}

/**
 * Deterministically generates an OpenAPI 3.1 specification document
 */
export function generateOpenApiSpec(schema: Flobase): Record<string, any> {
  const title = schema.name || "Flobase API";
  const version = String(schema.version || "0.1.0");
  const description = schema.description || "Deterministic REST API specification generated by Flobase";

  const components: { schemas: Record<string, any> } = {
    schemas: {}
  };

  // Generate component schemas for all models
  for (const [modelName, model] of Object.entries(schema.models)) {
    components.schemas[modelName] = buildModelSchema(model, "full");
    components.schemas[`${modelName}Input`] = buildModelSchema(model, "create");
  }

  const paths: Record<string, any> = {};

  if (schema.endpoints && schema.endpoints.length > 0) {
    for (const ep of schema.endpoints) {
      const normalizedPath = ep.path.startsWith("/") ? ep.path : `/${ep.path}`;
      if (!paths[normalizedPath]) {
        paths[normalizedPath] = {};
      }

      const methodLower = ep.method.toLowerCase();
      const associatedModel = ep.model ? schema.models[ep.model] : undefined;
      const modelName = ep.model;

      // Extract path parameters: e.g. /users/{id}
      const pathParams = (normalizedPath.match(/\{([^}]+)\}/g) || []).map((p) => p.slice(1, -1));
      const parameters = pathParams.map((paramName) => ({
        name: paramName,
        in: "path",
        required: true,
        schema: {
          type: "string"
        },
        description: `${paramName} identifier`
      }));

      const operation: Record<string, any> = {
        summary: ep.summary || `${ep.method} ${normalizedPath}`,
        responses: {
          "200": {
            description: "Successful response"
          }
        }
      };

      if (ep.description) {
        operation.description = ep.description;
      }

      if (parameters.length > 0) {
        operation.parameters = parameters;
      }

      // If associated model exists, wire up typed requestBody and responses
      if (modelName && associatedModel) {
        if (["post", "put", "patch"].includes(methodLower)) {
          operation.requestBody = {
            required: true,
            content: {
              "application/json": {
                schema: {
                  $ref: `#/components/schemas/${modelName}Input`
                }
              }
            }
          };
        }

        if (methodLower === "get") {
          // Check if path ends with parameter (single item) or not (list)
          const isItemRoute = pathParams.length > 0 && normalizedPath.endsWith(`{${pathParams[pathParams.length - 1]}}`);
          if (isItemRoute) {
            operation.responses["200"] = {
              description: `${modelName} details`,
              content: {
                "application/json": {
                  schema: {
                    $ref: `#/components/schemas/${modelName}`
                  }
                }
              }
            };
          } else {
            operation.responses["200"] = {
              description: `List of ${modelName} items`,
              content: {
                "application/json": {
                  schema: {
                    type: "array",
                    items: {
                      $ref: `#/components/schemas/${modelName}`
                    }
                  }
                }
              }
            };
          }
        } else if (methodLower === "post") {
          operation.responses = {
            "201": {
              description: `${modelName} created successfully`,
              content: {
                "application/json": {
                  schema: {
                    $ref: `#/components/schemas/${modelName}`
                  }
                }
              }
            }
          };
        } else if (methodLower === "delete") {
          operation.responses = {
            "204": {
              description: `${modelName} deleted successfully`
            }
          };
        }
      }

      paths[normalizedPath][methodLower] = operation;
    }
  }

  return {
    openapi: "3.1.0",
    info: {
      title,
      version,
      description
    },
    paths,
    components
  };
}

/**
 * Serializes the OpenAPI 3.1 specification to YAML string
 */
export function generateOpenApiYaml(schema: Flobase): string {
  const spec = generateOpenApiSpec(schema);
  const commentHeader = "# Generated by Flobase. Do not edit directly.\n";
  return commentHeader + yaml.stringify(spec, { indent: 2 });
}
