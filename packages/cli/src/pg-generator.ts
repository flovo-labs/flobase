import { Flobase, Model, Field } from "./schema.js";

/**
 * Maps Flobase abstract field types to PostgreSQL native types.
 * Standard mappings:
 *   uuid      -> UUID
 *   string    -> TEXT
 *   text      -> TEXT
 *   int       -> INTEGER
 *   integer   -> INTEGER
 *   decimal   -> NUMERIC(19,4)
 *   float     -> DOUBLE PRECISION
 *   bool      -> BOOLEAN
 *   boolean   -> BOOLEAN
 *   timestamp -> TIMESTAMPTZ
 *   datetime  -> TIMESTAMPTZ
 *   date      -> DATE
 *   time      -> TIME
 *   json      -> JSONB
 */
export function mapFieldToPostgresType(field: Field): string {
  const typeLower = (field.type || "string").toLowerCase();

  switch (typeLower) {
    case "uuid":
      return "UUID";
    case "string":
    case "text":
      return "TEXT";
    case "int":
    case "integer":
      return "INTEGER";
    case "float":
      return "DOUBLE PRECISION";
    case "decimal":
      return "NUMERIC(19,4)";
    case "bool":
    case "boolean":
      return "BOOLEAN";
    case "timestamp":
    case "datetime":
      return "TIMESTAMPTZ";
    case "date":
      return "DATE";
    case "time":
      return "TIME";
    case "json":
      return "JSONB";
    default:
      if (field.enum && field.enum.length > 0) {
        return "TEXT";
      }
      return "TEXT";
  }
}

/**
 * Helper to resolve target table name for a model name
 */
function resolveTableName(modelName: string, schema: Flobase): string {
  const model = schema.models[modelName];
  if (model?.tableName) {
    return model.tableName;
  }
  return toSnakeCase(modelName);
}

function toSnakeCase(str: string): string {
  return str
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[\s-]+/g, "_")
    .toLowerCase();
}

/**
 * Deterministically generates PostgreSQL DDL statements for all models in the schema.
 */
export function generatePostgresDDL(schema: Flobase): string {
  const lines: string[] = [
    "-- Generated by Flobase. Do not edit directly.",
    ""
  ];

  // Topologically sort or order models: models with no foreign key dependencies first
  const modelEntries = Object.entries(schema.models);
  const orderedModels = orderModelsByDependencies(modelEntries, schema);

  for (const [modelName, model] of orderedModels) {
    const tableName = resolveTableName(modelName, schema);
    lines.push(`CREATE TABLE IF NOT EXISTS ${tableName} (`);

    const columnDefs: string[] = [];
    const constraints: string[] = [];

    for (const [fieldName, field] of Object.entries(model.fields || {})) {
      const colName = toSnakeCase(fieldName);
      const pgType = mapFieldToPostgresType(field);
      const parts: string[] = [`  ${colName} ${pgType}`];

      // Primary Key
      if (field.primaryKey || field.primary) {
        parts.push("PRIMARY KEY");
      } else {
        // Unique
        if (field.unique) {
          parts.push("UNIQUE");
        }
        // Required / Nullable
        if (field.required || field.nullable === false) {
          parts.push("NOT NULL");
        }
      }

      // Default values
      if (field.default !== undefined) {
        if (typeof field.default === "string") {
          parts.push(`DEFAULT '${field.default.replace(/'/g, "''")}'`);
        } else if (typeof field.default === "number" || typeof field.default === "boolean") {
          parts.push(`DEFAULT ${field.default}`);
        } else if (field.default === null) {
          parts.push("DEFAULT NULL");
        }
      }

      // References (Foreign Key)
      if (field.references) {
        const [refModel, refField] = field.references.split(".");
        const targetTable = resolveTableName(refModel, schema);
        const targetCol = refField ? toSnakeCase(refField) : "id";
        parts.push(`REFERENCES ${targetTable}(${targetCol})`);
      }

      // Inline Enum check constraint
      if (field.enum && field.enum.length > 0) {
        const allowed = field.enum.map((v) => `'${v.replace(/'/g, "''")}'`).join(", ");
        parts.push(`CHECK (${colName} IN (${allowed}))`);
      }

      columnDefs.push(parts.join(" "));
    }

    const allLines = [...columnDefs, ...constraints];
    lines.push(allLines.join(",\n"));
    lines.push(");");
    lines.push("");

    // Create indexes if specified
    if (model.indexes && model.indexes.length > 0) {
      for (const idx of model.indexes) {
        if (typeof idx === "string") {
          const colName = toSnakeCase(idx);
          const indexName = `idx_${tableName}_${colName}`;
          lines.push(`CREATE INDEX IF NOT EXISTS ${indexName} ON ${tableName} (${colName});`);
        } else if (Array.isArray(idx)) {
          const colNames = idx.map(toSnakeCase).join(", ");
          const indexName = `idx_${tableName}_${idx.map(toSnakeCase).join("_")}`;
          lines.push(`CREATE INDEX IF NOT EXISTS ${indexName} ON ${tableName} (${colNames});`);
        }
      }
      lines.push("");
    }
  }

  return lines.join("\n").trim() + "\n";
}

/**
 * Topologically sorts models so referenced tables are created before dependent tables.
 */
function orderModelsByDependencies(
  entries: [string, Model][],
  schema: Flobase
): [string, Model][] {
  const result: [string, Model][] = [];
  const visited = new Set<string>();
  const visiting = new Set<string>();

  const modelMap = new Map(entries);

  function visit(name: string) {
    if (visited.has(name)) return;
    if (visiting.has(name)) {
      // Circular reference detected; break cycle gracefully
      return;
    }

    visiting.add(name);
    const model = modelMap.get(name);
    if (model && model.fields) {
      for (const field of Object.values(model.fields)) {
        if (field.references) {
          const [refModel] = field.references.split(".");
          if (refModel && refModel !== name && modelMap.has(refModel)) {
            visit(refModel);
          }
        }
      }
    }

    visiting.delete(name);
    visited.add(name);
    if (model) {
      result.push([name, model]);
    }
  }

  for (const [name] of entries) {
    visit(name);
  }

  return result;
}
