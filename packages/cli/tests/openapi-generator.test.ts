import { describe, it, expect } from "vitest";
import SwaggerParser from "@apidevtools/swagger-parser";
import { parseAndValidateSchema } from "../src/schema.js";
import { generateOpenApiSpec, generateOpenApiYaml } from "../src/openapi-generator.js";

const FIXTURE_SCHEMA = `
version: "0.1.0"
name: "StoreApi"
description: "Store REST API contract"
models:
  Product:
    fields:
      id:
        type: uuid
        primary: true
      title:
        type: string
        required: true
      price:
        type: decimal
        required: true
      inStock:
        type: bool
        default: true

endpoints:
  - method: GET
    path: /api/products
    summary: "List all products"
    model: Product

  - method: POST
    path: /api/products
    summary: "Create product"
    model: Product

  - method: GET
    path: /api/products/{id}
    summary: "Get product details"
    model: Product

  - method: DELETE
    path: /api/products/{id}
    summary: "Delete product"
    model: Product
`;

describe("OpenAPI 3.1 Generator", () => {
  it("generates an OpenAPI 3.1 object structure", () => {
    const parsed = parseAndValidateSchema(FIXTURE_SCHEMA);
    expect(parsed.success).toBe(true);

    const spec = generateOpenApiSpec(parsed.data!);
    expect(spec.openapi).toBe("3.1.0");
    expect(spec.info.title).toBe("StoreApi");
    expect(spec.paths["/api/products"]).toBeDefined();
    expect(spec.paths["/api/products"].get).toBeDefined();
    expect(spec.paths["/api/products"].post).toBeDefined();
    expect(spec.paths["/api/products/{id}"].get).toBeDefined();
  });

  it("passes swagger-parser.validate() without errors", async () => {
    const parsed = parseAndValidateSchema(FIXTURE_SCHEMA);
    expect(parsed.success).toBe(true);

    const spec = generateOpenApiSpec(parsed.data!);

    // swagger-parser validation
    const validated = await SwaggerParser.validate(spec as any);
    expect(validated).toBeDefined();
    expect(validated.info.title).toBe("StoreApi");
  });

  it("outputs valid YAML with header comment", () => {
    const parsed = parseAndValidateSchema(FIXTURE_SCHEMA);
    expect(parsed.success).toBe(true);

    const yamlStr = generateOpenApiYaml(parsed.data!);
    expect(yamlStr).toContain("# Generated by Flobase. Do not edit directly.");
    expect(yamlStr).toContain("openapi: 3.1.0");
  });
});
